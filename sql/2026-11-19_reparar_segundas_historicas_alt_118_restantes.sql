SET XACT_ABORT ON;
BEGIN TRANSACTION;

DECLARE @ID_ALTA BIGINT = 118;
DECLARE @CODIGO_ALTA VARCHAR(50) = 'ALT-20261119-F34EA2C3';

IF NOT EXISTS (
  SELECT 1 FROM dbo.ALTAS_PRODUCTOS
  WHERE ID_ALTA = @ID_ALTA AND CODIGO_ALTA = @CODIGO_ALTA AND ESTADO = 'BORRADOR'
)
  THROW 51000, 'El Alta esperada no existe o ya no se encuentra en BORRADOR.', 1;

IF EXISTS (SELECT 1 FROM dbo.ALTAS_PRODUCTOS_EXPORTADOS WHERE ID_ALTA = @ID_ALTA)
  THROW 51000, 'El Alta posee exportaciones y no puede repararse automáticamente.', 1;

IF EXISTS (SELECT 1 FROM dbo.PEDIDOS_ALTAS WHERE ID_ALTA = @ID_ALTA)
  THROW 51000, 'El Alta está asociada a un Pedido y no puede repararse automáticamente.', 1;

DECLARE @MAPEO TABLE (
  ID_DETALLE BIGINT PRIMARY KEY,
  CODIGO_ACTUAL VARCHAR(30) NOT NULL,
  CODIGO_HISTORICO VARCHAR(30) NOT NULL,
  CODIGO_ERP VARCHAR(50) NULL,
  EAN VARCHAR(50) NULL
);

INSERT INTO @MAPEO (ID_DETALLE, CODIGO_ACTUAL, CODIGO_HISTORICO, CODIGO_ERP, EAN)
SELECT
  D.ID_DETALLE,
  D.CODIGO_ALFA,
  H.CODIGO_ALFA,
  H.CODIGO,
  H.CODIGO_EAN
FROM dbo.ALTAS_PRODUCTOS_DETALLE D
INNER JOIN dbo.PRODUCTOS H
  ON H.ID_EMPRESA = D.ID_EMPRESA
 AND H.CODIGO_ALFA = LEFT(D.CODIGO_ALFA, 4)
   + SUBSTRING(D.CODIGO_ALFA, 6, 5)
   + ' '
   + SUBSTRING(D.CODIGO_ALFA, 11, 5)
 AND H.ACTIVO = 1
WHERE
  D.ID_ALTA = @ID_ALTA
  AND D.CODIGO_MODELO IN ('MT531', 'MT533')
  AND D.CODIGO_CLASIFICACION = '2'
  AND D.GENERADO_AUTOMATICO = 1
  AND D.CODIGO_ALFA NOT LIKE '% %';

IF (SELECT COUNT(*) FROM @MAPEO) <> 31
  THROW 51000, 'No se encontraron exactamente las 31 segundas históricas esperadas.', 1;

IF EXISTS (
  SELECT 1
  FROM @MAPEO M
  INNER JOIN dbo.ALTAS_PRODUCTOS_DETALLE D
    ON D.CODIGO_ALFA = M.CODIGO_HISTORICO
   AND D.ID_DETALLE <> M.ID_DETALLE
)
  THROW 51000, 'Una segunda histórica ya está registrada en otra Alta.', 1;

UPDATE D
SET
  D.CODIGO_ALFA = M.CODIGO_HISTORICO,
  D.ESTADO_VALIDACION = 'EXISTE_ERP',
  D.OBSERVACION_VALIDACION = CONCAT(
    'Ya existe en Presea | Código ERP: ', M.CODIGO_ERP,
    CASE WHEN NULLIF(M.EAN, '') IS NULL THEN '' ELSE CONCAT(' | EAN: ', M.EAN) END
  )
FROM dbo.ALTAS_PRODUCTOS_DETALLE D
INNER JOIN @MAPEO M ON M.ID_DETALLE = D.ID_DETALLE;

SELECT ID_DETALLE, CODIGO_ACTUAL, CODIGO_HISTORICO, CODIGO_ERP, EAN
FROM @MAPEO
ORDER BY CODIGO_HISTORICO;

COMMIT TRANSACTION;

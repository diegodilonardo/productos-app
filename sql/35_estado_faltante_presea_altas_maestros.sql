SET NOCOUNT ON;
SET XACT_ABORT ON;

BEGIN TRANSACTION;

IF OBJECT_ID('dbo.ALTAS_MAESTROS', 'U') IS NOT NULL
BEGIN
    IF EXISTS (
        SELECT 1
        FROM sys.check_constraints
        WHERE parent_object_id = OBJECT_ID('dbo.ALTAS_MAESTROS')
          AND name = 'CK_AM_ESTADO'
    )
        ALTER TABLE dbo.ALTAS_MAESTROS DROP CONSTRAINT CK_AM_ESTADO;

    ALTER TABLE dbo.ALTAS_MAESTROS WITH CHECK ADD CONSTRAINT CK_AM_ESTADO
        CHECK (ESTADO IN (
            'BORRADOR',
            'PENDIENTE_ENVIO',
            'ENVIADO_PRESEA',
            'CONFIRMADO_ERP',
            'FALTANTE_PRESEA',
            'ANULADO'
        ));

    ALTER TABLE dbo.ALTAS_MAESTROS CHECK CONSTRAINT CK_AM_ESTADO;
END;

COMMIT TRANSACTION;

SET NOCOUNT ON;
SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID('dbo.ALTAS_MAESTROS_DESTINOS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.ALTAS_MAESTROS_DESTINOS (
        ID_DESTINO INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        ID_EMPRESA INT NOT NULL,
        MARCA VARCHAR(50) NOT NULL,
        LICENCIA VARCHAR(50) NOT NULL,
        RUBRO VARCHAR(50) NOT NULL,
        RUTA_DESTINO VARCHAR(500) NOT NULL,
        ACTIVO BIT NOT NULL CONSTRAINT DF_AMD_ACTIVO DEFAULT (1),
        FECHA_ACTUALIZACION DATETIME2(0) NOT NULL CONSTRAINT DF_AMD_FECHA DEFAULT (SYSDATETIME()),
        CONSTRAINT FK_AMD_EMPRESA FOREIGN KEY (ID_EMPRESA) REFERENCES dbo.EMPRESAS(ID_EMPRESA),
        CONSTRAINT UQ_AMD_DESTINO UNIQUE (ID_EMPRESA, MARCA, LICENCIA, RUBRO)
    );
END;

DECLARE @DESTINOS TABLE (CODIGO_EMPRESA VARCHAR(30), MARCA VARCHAR(50), LICENCIA VARCHAR(50), RUBRO VARCHAR(50), RUTA_DESTINO VARCHAR(500));

;WITH RUBROS AS (
    SELECT RUBRO FROM (VALUES ('CALZADO'),('INDUMENTARIA'),('ACCESORIOS'),('POP')) R(RUBRO)
), BASE AS (
    SELECT * FROM (VALUES
      ('0','ATOMIK','/ALTAS_MAESTROS/VICBOR/ATOMIK'),
      ('3000','47 STREET','/ALTAS_MAESTROS/MIDING/47_STREET'),
      ('3000','MONTAGNE','/ALTAS_MAESTROS/MIDING/MONTAGNE'),
      ('3000','VANTEK','/ALTAS_MAESTROS/MIDING/VANTEK'),
      ('70000','MASSIMO','/ALTAS_MAESTROS/GYD/MASSIMO'),
      ('70000','MARCEL','/ALTAS_MAESTROS/GYD/MARCEL'),
      ('70000','WAKE','/ALTAS_MAESTROS/GYD/WAKE'),
      ('15000','BAGUNZA','/ALTAS_MAESTROS/BAGUNZA/BAGUNZA')
    ) B(CODIGO_EMPRESA,MARCA,RUTA_BASE)
)
INSERT @DESTINOS
SELECT B.CODIGO_EMPRESA,B.MARCA,'SIN_LICENCIA',R.RUBRO,CONCAT(B.RUTA_BASE,'/',R.RUBRO)
FROM BASE B CROSS JOIN RUBROS R;

;WITH RUBROS AS (
    SELECT RUBRO FROM (VALUES ('CALZADO'),('INDUMENTARIA'),('ACCESORIOS'),('POP')) R(RUBRO)
), LICENCIAS AS (
    SELECT LICENCIA FROM (VALUES ('SAN_LORENZO'),('TALLERES'),('VELEZ_SARSFIELD')) L(LICENCIA)
)
INSERT @DESTINOS
SELECT '0','ATOMIK',L.LICENCIA,R.RUBRO,CONCAT('/ALTAS_MAESTROS/VICBOR/ATOMIK/LICENCIAS/',L.LICENCIA,'/',R.RUBRO)
FROM LICENCIAS L CROSS JOIN RUBROS R;

MERGE dbo.ALTAS_MAESTROS_DESTINOS D
USING (
    SELECT E.ID_EMPRESA,S.MARCA,S.LICENCIA,S.RUBRO,S.RUTA_DESTINO
    FROM @DESTINOS S INNER JOIN dbo.EMPRESAS E ON LTRIM(RTRIM(E.CODIGO_EMPRESA))=S.CODIGO_EMPRESA
) O
ON D.ID_EMPRESA=O.ID_EMPRESA AND D.MARCA=O.MARCA AND D.LICENCIA=O.LICENCIA AND D.RUBRO=O.RUBRO
WHEN MATCHED THEN UPDATE SET RUTA_DESTINO=O.RUTA_DESTINO,ACTIVO=1,FECHA_ACTUALIZACION=SYSDATETIME()
WHEN NOT MATCHED THEN INSERT(ID_EMPRESA,MARCA,LICENCIA,RUBRO,RUTA_DESTINO)
VALUES(O.ID_EMPRESA,O.MARCA,O.LICENCIA,O.RUBRO,O.RUTA_DESTINO);

COMMIT TRANSACTION;

SELECT E.RAZON_SOCIAL,D.MARCA,D.LICENCIA,D.RUBRO,D.RUTA_DESTINO,D.ACTIVO
FROM dbo.ALTAS_MAESTROS_DESTINOS D INNER JOIN dbo.EMPRESAS E ON E.ID_EMPRESA=D.ID_EMPRESA
ORDER BY E.ID_EMPRESA,D.MARCA,D.LICENCIA,D.RUBRO;

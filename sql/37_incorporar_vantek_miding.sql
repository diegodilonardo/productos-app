SET NOCOUNT ON;
SET XACT_ABORT ON;

DECLARE @CODIGO_EMPRESA VARCHAR(30) = '3000';
DECLARE @CODIGO_MARCA VARCHAR(5) = '80';
DECLARE @DETALLE_MARCA VARCHAR(100) = 'VANTEK';
DECLARE @ID_EMPRESA INT;
DECLARE @ID_EMPRESA_MARCA INT;

SELECT @ID_EMPRESA = E.ID_EMPRESA
FROM dbo.EMPRESAS E
WHERE LTRIM(RTRIM(E.CODIGO_EMPRESA)) = @CODIGO_EMPRESA
   OR UPPER(LTRIM(RTRIM(E.RAZON_SOCIAL))) = 'MIDING';

IF @ID_EMPRESA IS NULL
    THROW 51070, 'No se encontro la empresa MIDING (codigo 3000).', 1;

BEGIN TRY
    BEGIN TRANSACTION;

    UPDATE dbo.MAESTRO_MARCAS
    SET DETALLE_MARCA = @DETALLE_MARCA,
        ACTIVO = 1,
        FECHA_ACTUALIZACION = SYSDATETIME()
    WHERE ID_EMPRESA = @ID_EMPRESA
      AND CODIGO_MARCA = @CODIGO_MARCA;

    IF @@ROWCOUNT = 0
    BEGIN
        INSERT INTO dbo.MAESTRO_MARCAS
        (
            ID_EMPRESA,
            CODIGO_MARCA,
            DETALLE_MARCA,
            OBSERVACION,
            ACTIVO
        )
        VALUES
        (
            @ID_EMPRESA,
            @CODIGO_MARCA,
            @DETALLE_MARCA,
            'Alta de marca VANTEK para MIDING',
            1
        );
    END;

    UPDATE dbo.EMPRESAS_MARCAS
    SET ACTIVA = 1
    WHERE ID_EMPRESA = @ID_EMPRESA
      AND CODIGO_MARCA = @CODIGO_MARCA;

    IF @@ROWCOUNT = 0
    BEGIN
        INSERT INTO dbo.EMPRESAS_MARCAS
        (
            ID_EMPRESA,
            CODIGO_MARCA,
            ACTIVA
        )
        VALUES
        (
            @ID_EMPRESA,
            @CODIGO_MARCA,
            1
        );
    END;

    SELECT @ID_EMPRESA_MARCA = ID_EMPRESA_MARCA
    FROM dbo.EMPRESAS_MARCAS
    WHERE ID_EMPRESA = @ID_EMPRESA
      AND CODIGO_MARCA = @CODIGO_MARCA;

    UPDATE dbo.EMPRESAS_MARCAS_EXPORT_CONFIG
    SET FTP_RUTA_EXPORTACION = '/ALTAS_PRODUCTOS/MIDING/VANTEK',
        FTP_ARCHIVO_PRODUCTOS = 'ALTAS_PRODUCTOS.DBI',
        FTP_ARCHIVO_MODELOS = 'MODELOS_VANTEK_TBL_PRODBASE.DBI',
        FTP_ARCHIVO_PRIMERAS_SEGUNDAS = 'PRIMERAS_SEGUNDAS_VANTEK.DBI',
        FTP_ARCHIVO_RELFORMU = 'PRODUCTOS_RELFORMU.DBI',
        FTP_ARCHIVO_RELACION = 'PRODUCTOS_RELACION.DBI',
        ACTIVA = 1,
        FECHA_ACTUALIZACION = SYSDATETIME()
    WHERE ID_EMPRESA_MARCA = @ID_EMPRESA_MARCA;

    IF @@ROWCOUNT = 0
    BEGIN
        INSERT INTO dbo.EMPRESAS_MARCAS_EXPORT_CONFIG
        (
            ID_EMPRESA_MARCA,
            FTP_RUTA_EXPORTACION,
            FTP_ARCHIVO_PRODUCTOS,
            FTP_ARCHIVO_MODELOS,
            FTP_ARCHIVO_PRIMERAS_SEGUNDAS,
            FTP_ARCHIVO_RELFORMU,
            FTP_ARCHIVO_RELACION,
            ACTIVA
        )
        VALUES
        (
            @ID_EMPRESA_MARCA,
            '/ALTAS_PRODUCTOS/MIDING/VANTEK',
            'ALTAS_PRODUCTOS.DBI',
            'MODELOS_VANTEK_TBL_PRODBASE.DBI',
            'PRIMERAS_SEGUNDAS_VANTEK.DBI',
            'PRODUCTOS_RELFORMU.DBI',
            'PRODUCTOS_RELACION.DBI',
            1
        );
    END;

    UPDATE dbo.PEDIDOS_EXPORT_CONFIG
    SET RUTA_PEDIDO_EXCEL = 'PEDIDOS\MIDING\VANTEK',
        RUTA_MASTER_DATA_APP = 'PEDIDOS\MIDING\VANTEK',
        RUTA_PREC_FOB = 'PEDIDOS\MIDING\VANTEK',
        ACTIVA = 1,
        FECHA_ACTUALIZACION = SYSDATETIME()
    WHERE ID_EMPRESA_MARCA = @ID_EMPRESA_MARCA;

    IF @@ROWCOUNT = 0
    BEGIN
        INSERT INTO dbo.PEDIDOS_EXPORT_CONFIG
        (
            ID_EMPRESA_MARCA,
            RUTA_PEDIDO_EXCEL,
            RUTA_MASTER_DATA_APP,
            RUTA_PREC_FOB,
            ACTIVA
        )
        VALUES
        (
            @ID_EMPRESA_MARCA,
            'PEDIDOS\MIDING\VANTEK',
            'PEDIDOS\MIDING\VANTEK',
            'PEDIDOS\MIDING\VANTEK',
            1
        );
    END;

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;

SELECT
    E.CODIGO_EMPRESA,
    E.RAZON_SOCIAL,
    MM.CODIGO_MARCA,
    MM.DETALLE_MARCA,
    MM.ACTIVO,
    EM.ID_EMPRESA_MARCA,
    EM.ACTIVA,
    AC.FTP_RUTA_EXPORTACION,
    AC.FTP_ARCHIVO_PRODUCTOS,
    AC.FTP_ARCHIVO_MODELOS,
    PC.RUTA_PEDIDO_EXCEL,
    PC.RUTA_MASTER_DATA_APP,
    PC.RUTA_PREC_FOB
FROM dbo.EMPRESAS E
INNER JOIN dbo.MAESTRO_MARCAS MM
    ON MM.ID_EMPRESA = E.ID_EMPRESA
INNER JOIN dbo.EMPRESAS_MARCAS EM
    ON EM.ID_EMPRESA = E.ID_EMPRESA
   AND EM.CODIGO_MARCA = MM.CODIGO_MARCA
LEFT JOIN dbo.EMPRESAS_MARCAS_EXPORT_CONFIG AC
    ON AC.ID_EMPRESA_MARCA = EM.ID_EMPRESA_MARCA
LEFT JOIN dbo.PEDIDOS_EXPORT_CONFIG PC
    ON PC.ID_EMPRESA_MARCA = EM.ID_EMPRESA_MARCA
WHERE E.ID_EMPRESA = @ID_EMPRESA
  AND MM.CODIGO_MARCA = @CODIGO_MARCA;

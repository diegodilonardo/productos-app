MERGE dbo.REGLAS_RUBRO_FACT AS DESTINO
USING
(
    SELECT
        E.ID_EMPRESA,
        R.MARCA_EMPRESA,
        R.CODIGO_RUBRO,
        R.TIPO_PRODUCTO,
        R.RUBRO_FACTURACION
    FROM @REGLAS R
    INNER JOIN dbo.EMPRESAS E
        ON LTRIM(RTRIM(E.CODIGO_EMPRESA)) = R.CODIGO_EMPRESA
) AS ORIGEN
ON DESTINO.ID_EMPRESA = ORIGEN.ID_EMPRESA
AND UPPER(LTRIM(RTRIM(DESTINO.MARCA_EMPRESA))) = UPPER(LTRIM(RTRIM(ORIGEN.MARCA_EMPRESA)))
AND UPPER(LTRIM(RTRIM(DESTINO.CODIGO_RUBRO))) = UPPER(LTRIM(RTRIM(ORIGEN.CODIGO_RUBRO)))
AND DESTINO.TIPO_PRODUCTO = ORIGEN.TIPO_PRODUCTO
WHEN MATCHED THEN
    UPDATE SET
        DESTINO.RUBRO_FACTURACION = ORIGEN.RUBRO_FACTURACION,
        DESTINO.ACTIVA = 1,
        DESTINO.FECHA_ACTUALIZACION = SYSDATETIME()
WHEN NOT MATCHED THEN
    INSERT
    (
        ID_EMPRESA,
        MARCA_EMPRESA,
        CODIGO_RUBRO,
        TIPO_PRODUCTO,
        RUBRO_FACTURACION,
        ACTIVA
    )
    VALUES
    (
        ORIGEN.ID_EMPRESA,
        ORIGEN.MARCA_EMPRESA,
        ORIGEN.CODIGO_RUBRO,
        ORIGEN.TIPO_PRODUCTO,
        ORIGEN.RUBRO_FACTURACION,
        1
    );


CREATE OR ALTER PROCEDURE dbo.CONFIGURAR_REGLA_RUBRO_FACT
    @CODIGO_EMPRESA VARCHAR(30),
    @MARCA_EMPRESA VARCHAR(100),
    @CODIGO_RUBRO VARCHAR(50),
    @TIPO_PRODUCTO VARCHAR(20),
    @RUBRO_FACTURACION VARCHAR(30),
    @ACTIVA BIT = 1
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    SELECT
        @CODIGO_EMPRESA = LTRIM(RTRIM(@CODIGO_EMPRESA)),
        @MARCA_EMPRESA = UPPER(LTRIM(RTRIM(@MARCA_EMPRESA))),
        @CODIGO_RUBRO = UPPER(LTRIM(RTRIM(@CODIGO_RUBRO))),
        @TIPO_PRODUCTO = UPPER(LTRIM(RTRIM(@TIPO_PRODUCTO))),
        @RUBRO_FACTURACION = LTRIM(RTRIM(@RUBRO_FACTURACION));

    IF @TIPO_PRODUCTO NOT IN ('MODULO', 'PAR_SUELTO')
        THROW 51100, 'TIPO_PRODUCTO debe ser MODULO o PAR_SUELTO.', 1;

    DECLARE @ID_EMPRESA INT;

    SELECT @ID_EMPRESA = ID_EMPRESA
    FROM dbo.EMPRESAS
    WHERE LTRIM(RTRIM(CODIGO_EMPRESA)) = @CODIGO_EMPRESA
      AND ACTIVA = 1;

    IF @ID_EMPRESA IS NULL
        THROW 51101, 'La empresa indicada no existe o esta inactiva.', 1;

    IF @ACTIVA = 1
       AND NOT EXISTS
       (
           SELECT 1
           FROM dbo.MAESTRO_RUBRO_FACT
           WHERE ID_EMPRESA = @ID_EMPRESA
             AND UPPER(LTRIM(RTRIM(MARCA_EMPRESA))) = @MARCA_EMPRESA
             AND UPPER(LTRIM(RTRIM(RUBRO_FACTURACION))) = UPPER(@RUBRO_FACTURACION)
             AND ACTIVO = 1
       )
        THROW 51102, 'El RUBRO_FACT no existe activo en el maestro de Presea para esa empresa y marca.', 1;

    MERGE dbo.REGLAS_RUBRO_FACT AS D
    USING
    (
        SELECT
            @ID_EMPRESA AS ID_EMPRESA,
            @MARCA_EMPRESA AS MARCA_EMPRESA,
            @CODIGO_RUBRO AS CODIGO_RUBRO,
            @TIPO_PRODUCTO AS TIPO_PRODUCTO
    ) AS O
    ON D.ID_EMPRESA = O.ID_EMPRESA
    AND UPPER(LTRIM(RTRIM(D.MARCA_EMPRESA))) = O.MARCA_EMPRESA
    AND UPPER(LTRIM(RTRIM(D.CODIGO_RUBRO))) = O.CODIGO_RUBRO
    AND D.TIPO_PRODUCTO = O.TIPO_PRODUCTO
    WHEN MATCHED THEN
        UPDATE SET
            D.RUBRO_FACTURACION = @RUBRO_FACTURACION,
            D.ACTIVA = @ACTIVA,
            D.FECHA_ACTUALIZACION = SYSDATETIME()
    WHEN NOT MATCHED THEN
        INSERT
        (
            ID_EMPRESA,
            MARCA_EMPRESA,
            CODIGO_RUBRO,
            TIPO_PRODUCTO,
            RUBRO_FACTURACION,
            ACTIVA
        )
        VALUES
        (
            @ID_EMPRESA,
            @MARCA_EMPRESA,
            @CODIGO_RUBRO,
            @TIPO_PRODUCTO,
            @RUBRO_FACTURACION,
            @ACTIVA
        );

    SELECT
        E.CODIGO_EMPRESA,
        E.RAZON_SOCIAL,
        R.MARCA_EMPRESA,
        R.CODIGO_RUBRO,
        R.TIPO_PRODUCTO,
        R.RUBRO_FACTURACION,
        R.ACTIVA,
        R.FECHA_ACTUALIZACION
    FROM dbo.REGLAS_RUBRO_FACT R
    INNER JOIN dbo.EMPRESAS E ON E.ID_EMPRESA = R.ID_EMPRESA
    WHERE R.ID_EMPRESA = @ID_EMPRESA
      AND UPPER(LTRIM(RTRIM(R.MARCA_EMPRESA))) = @MARCA_EMPRESA
      AND UPPER(LTRIM(RTRIM(R.CODIGO_RUBRO))) = @CODIGO_RUBRO
      AND R.TIPO_PRODUCTO = @TIPO_PRODUCTO;
END;

SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF COL_LENGTH('dbo.PEDIDOS', 'TIPO_PEDIDO') IS NULL
  ALTER TABLE dbo.PEDIDOS ADD TIPO_PEDIDO VARCHAR(20) NULL;
IF COL_LENGTH('dbo.PEDIDOS', 'CODIGO_MARCA') IS NULL
  ALTER TABLE dbo.PEDIDOS ADD CODIGO_MARCA VARCHAR(5) NULL;
IF COL_LENGTH('dbo.PEDIDOS', 'DETALLE_MARCA') IS NULL
  ALTER TABLE dbo.PEDIDOS ADD DETALLE_MARCA VARCHAR(100) NULL;

EXEC sys.sp_executesql N'
  UPDATE P
  SET TIPO_PEDIDO = COALESCE(NULLIF(LTRIM(RTRIM(P.TIPO_PEDIDO)), ''''), ''PRODUCTOS''),
      CODIGO_MARCA = COALESCE(P.CODIGO_MARCA, A.CODIGO_MARCA),
      DETALLE_MARCA = COALESCE(P.DETALLE_MARCA, A.DETALLE_MARCA)
  FROM dbo.PEDIDOS P
  LEFT JOIN dbo.ALTAS_PRODUCTOS A
    ON A.ID_EMPRESA = P.ID_EMPRESA AND A.ID_ALTA = P.ID_ALTA;';

EXEC sys.sp_executesql N'ALTER TABLE dbo.PEDIDOS ALTER COLUMN TIPO_PEDIDO VARCHAR(20) NOT NULL;';
ALTER TABLE dbo.PEDIDOS ALTER COLUMN ID_ALTA INT NULL;

IF NOT EXISTS (
  SELECT 1 FROM sys.default_constraints DC
  INNER JOIN sys.columns C ON C.object_id = DC.parent_object_id AND C.column_id = DC.parent_column_id
  WHERE DC.parent_object_id = OBJECT_ID('dbo.PEDIDOS') AND C.name = 'TIPO_PEDIDO'
)
  EXEC sys.sp_executesql N'ALTER TABLE dbo.PEDIDOS ADD CONSTRAINT DF_PEDIDOS_TIPO_PEDIDO DEFAULT (''PRODUCTOS'') FOR TIPO_PEDIDO;';

IF OBJECT_ID('dbo.CK_PEDIDOS_TIPO_PEDIDO', 'C') IS NULL
  EXEC sys.sp_executesql N'ALTER TABLE dbo.PEDIDOS ADD CONSTRAINT CK_PEDIDOS_TIPO_PEDIDO
    CHECK (TIPO_PEDIDO IN (''PRODUCTOS'', ''SERVICIOS''));';

COMMIT TRANSACTION;

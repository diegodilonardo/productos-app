SET NOCOUNT ON;

IF OBJECT_ID('dbo.PEDIDOS_REAPERTURAS', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.PEDIDOS_REAPERTURAS
  (
    ID_REAPERTURA BIGINT IDENTITY(1,1) NOT NULL,
    ID_EMPRESA INT NOT NULL,
    ID_PEDIDO BIGINT NOT NULL,
    ESTADO_ANTERIOR VARCHAR(20) NOT NULL,
    MOTIVO VARCHAR(500) NOT NULL,
    USUARIO VARCHAR(100) NOT NULL,
    EXPORTACIONES_OBSOLETAS INT NOT NULL CONSTRAINT DF_PEDIDOS_REAPERTURAS_EXPORTACIONES DEFAULT (0),
    FECHA_REAPERTURA DATETIME2(3) NOT NULL CONSTRAINT DF_PEDIDOS_REAPERTURAS_FECHA DEFAULT (SYSDATETIME()),
    CONSTRAINT PK_PEDIDOS_REAPERTURAS PRIMARY KEY (ID_REAPERTURA),
    CONSTRAINT FK_PEDIDOS_REAPERTURAS_PEDIDO FOREIGN KEY (ID_EMPRESA, ID_PEDIDO)
      REFERENCES dbo.PEDIDOS (ID_EMPRESA, ID_PEDIDO)
  );

  CREATE INDEX IX_PEDIDOS_REAPERTURAS_PEDIDO
    ON dbo.PEDIDOS_REAPERTURAS (ID_EMPRESA, ID_PEDIDO, FECHA_REAPERTURA DESC);
END;

SELECT COUNT(*) AS REAPERTURAS FROM dbo.PEDIDOS_REAPERTURAS;

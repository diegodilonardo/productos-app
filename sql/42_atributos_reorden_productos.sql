SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF COL_LENGTH('dbo.PRODUCTOS', 'CODIGO_GRUPO') IS NULL
  ALTER TABLE dbo.PRODUCTOS ADD CODIGO_GRUPO VARCHAR(2) NULL;
IF COL_LENGTH('dbo.PRODUCTOS', 'CODIGO_SUBGRUPO') IS NULL
  ALTER TABLE dbo.PRODUCTOS ADD CODIGO_SUBGRUPO VARCHAR(2) NULL;
IF COL_LENGTH('dbo.PRODUCTOS', 'CODIGO_LINEA') IS NULL
  ALTER TABLE dbo.PRODUCTOS ADD CODIGO_LINEA VARCHAR(4) NULL;

IF COL_LENGTH('dbo.PRODUCTOS_ERP_STAGING', 'CODIGO_GRUPO') IS NULL
  ALTER TABLE dbo.PRODUCTOS_ERP_STAGING ADD CODIGO_GRUPO VARCHAR(2) NULL;
IF COL_LENGTH('dbo.PRODUCTOS_ERP_STAGING', 'CODIGO_SUBGRUPO') IS NULL
  ALTER TABLE dbo.PRODUCTOS_ERP_STAGING ADD CODIGO_SUBGRUPO VARCHAR(2) NULL;
IF COL_LENGTH('dbo.PRODUCTOS_ERP_STAGING', 'CODIGO_LINEA') IS NULL
  ALTER TABLE dbo.PRODUCTOS_ERP_STAGING ADD CODIGO_LINEA VARCHAR(4) NULL;

COMMIT TRANSACTION;

SELECT
  COL_LENGTH('dbo.PRODUCTOS', 'CODIGO_GRUPO') AS PRODUCTOS_GRUPO,
  COL_LENGTH('dbo.PRODUCTOS', 'CODIGO_SUBGRUPO') AS PRODUCTOS_SUBGRUPO,
  COL_LENGTH('dbo.PRODUCTOS', 'CODIGO_LINEA') AS PRODUCTOS_LINEA,
  COL_LENGTH('dbo.PRODUCTOS_ERP_STAGING', 'CODIGO_GRUPO') AS STAGING_GRUPO,
  COL_LENGTH('dbo.PRODUCTOS_ERP_STAGING', 'CODIGO_SUBGRUPO') AS STAGING_SUBGRUPO,
  COL_LENGTH('dbo.PRODUCTOS_ERP_STAGING', 'CODIGO_LINEA') AS STAGING_LINEA;
